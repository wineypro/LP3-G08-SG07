package Ejer2;

public class Empleado {
    int id;
    String nombre;
    String cargo;
    double salario;
    int edad;

    public Empleado(int id, String nombre, String cargo, double salario, int edad) {
        this.id = id;
        this.nombre = nombre;
        this.cargo = cargo;
        this.salario = salario;
        this.edad = edad;
    }
}
